"""Precomputed chunks for the seed (F10-AC1, AC6) -> supabase/seed/04_chunks.sql.

The nightly reset must not call an LLM or embedding model (cost, availability). So the
chunks of the seed documents and their embeddings are computed once, with the real Mistral
model, and committed as SQL. `supabase db reset` and the nightly reset (scripts/reset_demo.py)
load every file in supabase/seed/ in name order - after 02_documents.sql, which the chunks
point to.

Run once by the applicant in their own terminal (reads only MISTRAL_API_KEY from the given
.env file and never prints it):

    make seed-chunks              (= cd apps/api && PYTHONPATH=../.. uv run python
                                     -m scripts.build_seed_chunks ../../.env)

Again only when the seed texts (samples/generate.py) or the chunker change - the test
tests/rls/test_seed_chunks.py says when.
"""

import asyncio
import sys
from pathlib import Path

from app.config import Settings
from app.providers.embeddings import DIMENSION, create_embedding_provider
from app.rag.chunker import split_pages
from samples.generate import RESIDENT_IDS, SEED_DOCUMENTS, WARD_OF
from scripts.provision_db_roles import read_env

SQL_PATH = Path(__file__).parents[3] / "supabase" / "seed" / "04_chunks.sql"


def seed_chunks() -> list[dict]:
    """One row per chunk of every seed document, with the document's metadata (the same
    the indexer stores for an approved upload, F05-AC1). Seed documents have one page."""
    rows = []
    for doc in SEED_DOCUMENTS:
        for chunk in split_pages([(1, "\n".join(doc["lines"]))]):
            rows.append(
                {
                    "document_id": doc["id"],
                    "ward_id": WARD_OF[doc["resident"]],
                    "resident_id": RESIDENT_IDS[doc["resident"]],
                    "doc_type": doc["doc_type"],
                    "document_date": doc["date"],
                    "page": chunk.page,
                    "heading": chunk.heading,
                    "content": chunk.content,
                }
            )
    return rows


def _text(value: str | None) -> str:
    """SQL literal with dollar quoting: quotes in the text cannot end the string."""
    return "null" if value is None else f"$chunk${value}$chunk$"


def render_sql(rows: list[dict], vectors: list[list[float]], model: str) -> str:
    if len(vectors) != len(rows) or any(len(v) != DIMENSION for v in vectors):
        raise ValueError(f"expected {len(rows)} vectors of {DIMENSION} numbers")
    out = [
        "-- Generated by apps/api/scripts/build_seed_chunks.py (`make seed-chunks`) - do not",
        "-- edit by hand. Chunks of the seed documents with precomputed embeddings, so the",
        "-- nightly reset needs no model call (F10-AC6).",
    ]
    for row, vector in zip(rows, vectors, strict=True):
        numbers = ",".join(format(x, ".6g") for x in vector)
        out.append(
            "insert into public.chunks (document_id, ward_id, resident_id, doc_type,"
            " document_date, page, heading, content, embedding, embedding_model) values"
            f" ('{row['document_id']}', '{row['ward_id']}', '{row['resident_id']}',"
            f" '{row['doc_type']}', '{row['document_date']}', {row['page']},"
            f" {_text(row['heading'])}, {_text(row['content'])},"
            f" '[{numbers}]'::extensions.vector, '{model}');"
        )
    ids = ", ".join(f"'{doc_id}'" for doc_id in dict.fromkeys(r["document_id"] for r in rows))
    out.append(f"update public.documents set indexing_status = 'done' where id in ({ids});")
    return "\n".join(out) + "\n"


async def build(env_file: Path) -> None:
    key = read_env(env_file).get("MISTRAL_API_KEY", "")
    if not key:
        raise SystemExit(f"MISTRAL_API_KEY fehlt in {env_file}.")
    settings = Settings(llm_provider="mistral", mistral_api_key=key)
    embeddings = create_embedding_provider(settings)
    rows = seed_chunks()
    vectors = await embeddings.embed([row["content"] for row in rows])
    SQL_PATH.write_text(render_sql(rows, vectors, embeddings.model_name), encoding="utf-8")
    print(f"{len(rows)} Chunks mit {embeddings.model_name} geschrieben nach {SQL_PATH}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("Aufruf: python -m scripts.build_seed_chunks <pfad/zur/.env>")
    asyncio.run(build(Path(sys.argv[1])))

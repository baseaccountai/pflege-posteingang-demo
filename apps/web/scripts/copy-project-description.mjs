// Phase 9: copies the project description (docs/projektbeschreibung.md, the only source)
// and its pictures (docs/assets/projekt/) into the web app - its Docker image sees only
// apps/web. A test fails when the copy is out of date. Run: make project-description
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DOCS = path.resolve(WEB, "../../docs");
const PICTURES = path.join(DOCS, "assets/projekt");
const PUBLIC = path.join(WEB, "public/projekt");

const text = readFileSync(path.join(DOCS, "projektbeschreibung.md"), "utf8");
writeFileSync(
  path.join(WEB, "src/content/project-description.ts"),
  "// Generated by `make project-description` from docs/projektbeschreibung.md - do not edit.\n" +
    `export const PROJECT_DESCRIPTION = ${JSON.stringify(text)};\n`,
);

rmSync(PUBLIC, { recursive: true, force: true });
mkdirSync(PUBLIC, { recursive: true });
for (const name of readdirSync(PICTURES)) copyFileSync(path.join(PICTURES, name), path.join(PUBLIC, name));
console.log(`project description: ${text.length} characters, ${readdirSync(PUBLIC).length} pictures`);
